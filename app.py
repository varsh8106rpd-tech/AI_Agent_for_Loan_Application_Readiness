import streamlit as st
from agent.orchestrator import run_readiness_agent

st.set_page_config(page_title="Loan Readiness Agent", page_icon="🧾", layout="wide")
st.title("🧾 Loan Application Readiness Agent")
st.caption("Synthetic-data demo • Application readiness only • No loan approval or rejection")

with st.sidebar:
    st.header("About this demo")
    st.write("The agent calls Python tools to validate fields, calculate financial summaries, check consistency, and verify its results.")
    st.warning("Do not enter real personal or financial information. This prototype uses synthetic data.")

st.subheader("Application details")
with st.form("application_form"):
    c1, c2 = st.columns(2)
    with c1:
        application_id = st.text_input("Application ID", value="SYN-001")
        applicant_name = st.text_input("Synthetic applicant name", value="Alex Sample")
        employment_type = st.selectbox("Employment type", ["Salaried", "Self-employed", "Other", ""])
        declared_income = st.number_input("Declared gross monthly income (₹)", min_value=0.0, value=60000.0, step=1000.0)
        record_income = st.number_input("Income shown in supplied records (₹)", min_value=0.0, value=60000.0, step=1000.0)
    with c2:
        monthly_expenses = st.number_input("Monthly living expenses (₹)", min_value=0.0, value=20000.0, step=1000.0)
        monthly_debt = st.number_input("Existing monthly debt payments (₹)", min_value=0.0, value=10000.0, step=1000.0)
        requested_amount = st.number_input("Requested loan amount (₹)", min_value=0.0, value=300000.0, step=10000.0)
        monthly_instalment = st.number_input("Proposed monthly instalment (₹, optional estimate)", min_value=0.0, value=0.0, step=500.0)

    st.markdown("**Required information / evidence supplied**")
    d1, d2, d3 = st.columns(3)
    with d1:
        identity_present = st.checkbox("Identity information", value=True)
    with d2:
        income_proof = st.checkbox("Income proof", value=True)
    with d3:
        bank_records = st.checkbox("Bank / financial records", value=True)

    submitted = st.form_submit_button("Run readiness agent", type="primary", use_container_width=True)

if submitted:
    application = {
        "application_id": application_id.strip(),
        "applicant_name": applicant_name.strip(),
        "employment_type": employment_type,
        "declared_monthly_income": declared_income,
        "record_monthly_income": record_income,
        "monthly_expenses": monthly_expenses,
        "monthly_debt_payments": monthly_debt,
        "requested_loan_amount": requested_amount,
        "proposed_monthly_instalment": monthly_instalment,
        "documents": {
            "identity_information": identity_present,
            "income_proof": income_proof,
            "bank_financial_records": bank_records,
        },
    }
    report = run_readiness_agent(application)
    st.divider()
    st.header("Readiness report")
    if report["status"] == "Ready for human review":
        st.success(report["status"])
    elif report["status"] == "Needs clarification":
        st.warning(report["status"])
    else:
        st.error(report["status"])

    st.info("This status concerns completeness and consistency only. It is not an assessment of creditworthiness or loan eligibility.")

    st.subheader("Financial summary")
    metrics = st.columns(4)
    metrics[0].metric("Gross monthly income", f"₹{report['financial_summary']['gross_monthly_income']:,.2f}")
    metrics[1].metric("Monthly outgoings", f"₹{report['financial_summary']['total_monthly_outgoings']:,.2f}")
    metrics[2].metric("Disposable income", f"₹{report['financial_summary']['disposable_income']:,.2f}")
    dti = report["financial_summary"]["debt_to_income_ratio_percent"]
    metrics[3].metric("Existing debt-to-income", "N/A" if dti is None else f"{dti:.2f}%")

    st.subheader("Findings")
    if report["findings"]:
        for finding in report["findings"]:
            st.write(f"- {finding}")
    else:
        st.write("No configured completeness or consistency issues were found.")

    st.subheader("Questions for the human reviewer")
    if report["reviewer_questions"]:
        for question in report["reviewer_questions"]:
            st.write(f"- {question}")
    else:
        st.write("No clarification questions generated by the configured checks.")

    with st.expander("Agent execution trace"):
        for step in report["execution_trace"]:
            st.write(f"{step['step']}. **{step['tool']}** — {step['result']}")

    st.download_button(
        "Download report as JSON",
        data=__import__("json").dumps(report, indent=2),
        file_name=f"{application_id or 'application'}_readiness_report.json",
        mime="application/json",
    )
